import os
import uuid
import pypdf
from fastapi import UploadFile, HTTPException

ALLOWED_EXTENSIONS = {".pdf", ".png", ".jpg", ".jpeg", ".txt"}
MAX_FILE_SIZE_BYTES = 15 * 1024 * 1024  # 15 MB


def validate_file(file: UploadFile) -> str:
    ext = os.path.splitext(file.filename)[1].lower()
    if ext not in ALLOWED_EXTENSIONS:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file type '{ext}'. Supported formats: PDF, PNG, JPG, JPEG, TXT.",
        )
    return ext


def save_upload_file(file: UploadFile, upload_dir: str) -> tuple[str, str, int]:
    os.makedirs(upload_dir, exist_ok=True)
    ext = validate_file(file)
    safe_filename = f"{uuid.uuid4().hex}_{os.path.basename(file.filename)}"
    destination = os.path.join(upload_dir, safe_filename)

    file_size = 0
    with open(destination, "wb") as buffer:
        while chunk := file.file.read(1024 * 64):
            file_size += len(chunk)
            if file_size > MAX_FILE_SIZE_BYTES:
                buffer.close()
                if os.path.exists(destination):
                    os.remove(destination)
                raise HTTPException(
                    status_code=400,
                    detail="File exceeds maximum allowed size of 15 MB.",
                )
            buffer.write(chunk)

    return destination, safe_filename, file_size


def extract_text_from_file(file_path: str, mime_type: str) -> str:
    ext = os.path.splitext(file_path)[1].lower()
    if ext == ".txt":
        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                return f.read()
        except Exception as e:
            return f"Note: text file read notice: {str(e)}"
    elif ext == ".pdf":
        try:
            reader = pypdf.PdfReader(file_path)
            extracted_pages = []
            for i, page in enumerate(reader.pages):
                text = page.extract_text()
                if text and text.strip():
                    extracted_pages.append(f"--- Page {i+1} ---\n{text.strip()}")
            if extracted_pages:
                return "\n\n".join(extracted_pages)
            return "Document scanned as images. Standard text could not be extracted directly."
        except Exception as e:
            return f"Note: PDF extraction completed with notice: {str(e)}"
    else:
        return f"Image document ({ext.upper()}) uploaded. Visual inspection summary generated by AI assistant."
